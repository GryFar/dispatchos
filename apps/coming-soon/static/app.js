const SUPPORTED_LANGS = ['en', 'ua', 'ru'];

function detectLang() {
  // 1. URL query (?lang=ua)
  const params = new URLSearchParams(location.search);
  const fromUrl = params.get('lang');
  if (fromUrl && SUPPORTED_LANGS.includes(fromUrl)) return fromUrl;

  // 2. Browser language
  const nav = (navigator.language || 'en').toLowerCase();
  if (nav.startsWith('uk')) return 'ua';
  if (nav.startsWith('ru')) return 'ru';
  if (nav.startsWith('en')) return 'en';

  // 3. Default
  return 'en';
}

function applyLang(lang) {
  const dict = I18N[lang] || I18N.en;
  document.documentElement.lang = lang === 'ua' ? 'uk' : lang;

  // Plain text nodes
  document.querySelectorAll('[data-i18n]').forEach((el) => {
    const key = el.getAttribute('data-i18n');
    if (dict[key] !== undefined) el.textContent = dict[key];
  });

  // HTML content (h1 with <br>, <em>)
  document.querySelectorAll('[data-i18n-html]').forEach((el) => {
    const key = el.getAttribute('data-i18n-html');
    if (dict[key] !== undefined) el.innerHTML = dict[key];
  });

  // Attributes (e.g. placeholder)
  document.querySelectorAll('[data-i18n-attr]').forEach((el) => {
    const spec = el.getAttribute('data-i18n-attr');
    spec.split(',').forEach((pair) => {
      const [attr, key] = pair.trim().split(':');
      if (attr && key && dict[key] !== undefined) el.setAttribute(attr, dict[key]);
    });
  });

  // Update lang switcher visual state
  document.querySelectorAll('.lang-btn').forEach((btn) => {
    btn.classList.toggle('is-active', btn.dataset.lang === lang);
    btn.setAttribute('aria-pressed', String(btn.dataset.lang === lang));
  });

  // Update title
  const titles = {
    en: 'DispatchOS — Coming Soon',
    ua: 'DispatchOS — Скоро запуск',
    ru: 'DispatchOS — Скоро запуск',
  };
  document.title = titles[lang] || titles.en;

  // Persist via URL (no localStorage allowed in some preview iframes)
  const url = new URL(location.href);
  if (lang !== 'en') url.searchParams.set('lang', lang);
  else url.searchParams.delete('lang');
  history.replaceState(null, '', url);
}

// Init lang
const initialLang = detectLang();
applyLang(initialLang);

// Lang switcher click handler
document.querySelectorAll('.lang-btn').forEach((btn) => {
  btn.addEventListener('click', () => applyLang(btn.dataset.lang));
});

// === Day counter ===
const PROJECT_START = new Date('2026-05-14T00:00:00-04:00');
const PROGRESS_TARGET = 75;

(function () {
  const now = new Date();
  const days = Math.max(0, Math.floor((now - PROJECT_START) / (1000 * 60 * 60 * 24)));
  const counter = document.getElementById('day-counter');
  if (counter) counter.textContent = days === 0 ? '1' : String(days);

  setTimeout(() => {
    const fill = document.getElementById('progress-fill');
    if (fill) fill.style.width = PROGRESS_TARGET + '%';
  }, 400);
})();

// === Email subscribe ===
(function () {
  const form = document.getElementById('subscribe-form');
  const input = document.getElementById('email-input');
  const btn = document.getElementById('submit-btn');
  const msg = document.getElementById('form-msg');
  if (!form) return;

  // Honeypot
  const hp = document.createElement('input');
  hp.type = 'text';
  hp.name = 'website';
  hp.tabIndex = -1;
  hp.autocomplete = 'off';
  hp.style.cssText = 'position:absolute;left:-9999px;width:1px;height:1px;opacity:0;';
  hp.setAttribute('aria-hidden', 'true');
  form.appendChild(hp);

  form.addEventListener('submit', async (e) => {
    e.preventDefault();
    msg.textContent = '';
    msg.className = 'form-msg';

    const lang = document.documentElement.lang === 'uk' ? 'ua' : (document.documentElement.lang || 'en');
    const dict = I18N[lang] || I18N.en;

    const email = input.value.trim();
    if (!email || !/^[^\s@]+@[^\s@]+\.[^\s@]+$/.test(email)) {
      msg.textContent = dict.msgInvalidEmail;
      msg.classList.add('error');
      input.focus();
      return;
    }

    if (hp.value) {
      btn.classList.add('is-done');
      input.disabled = true;
      return;
    }

    btn.classList.add('is-loading');
    btn.disabled = true;

    try {
      const res = await fetch('https://demo.dispatchos.co/api/public/subscribe', {
        method: 'POST',
        headers: { 'content-type': 'application/json' },
        body: JSON.stringify({
          email,
          lang,
          referer: document.referrer || undefined,
        }),
      });

      if (res.ok) {
        btn.classList.remove('is-loading');
        btn.classList.add('is-done');
        msg.textContent = dict.msgSuccess;
        msg.classList.add('success');
        input.disabled = true;
      } else {
        const body = await res.json().catch(() => ({}));
        throw new Error(body.error || 'Subscribe failed');
      }
    } catch (err) {
      btn.classList.remove('is-loading');
      btn.disabled = false;
      msg.textContent = dict.msgError;
      msg.classList.add('error');
      console.error(err);
    }
  });
})();
